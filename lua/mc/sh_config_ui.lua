--[[----------------------------------------------------------------------------
	MC : shared ConVar metadata for the in-game config menu.
------------------------------------------------------------------------------]]

MC = MC or {}

local function choice( value, label, labelZH )
	return {
		value = tostring( value ),
		label = label,
		labelZH = labelZH,
	}
end

local function item( name, label, labelZH, kind, help, helpZH, options )
	local entry = {
		name = name,
		label = label,
		labelZH = labelZH,
		kind = kind or "number",
		help = help or "",
		helpZH = helpZH or "",
	}

	for key, value in pairs( options or {} ) do
		entry[key] = value
	end

	return entry
end

local function category( id, group, label, labelZH, description, descriptionZH, items )
	for _, entry in ipairs( items or {} ) do
		entry.category = id
	end

	return {
		id = id,
		group = group,
		label = label,
		zhLabel = labelZH,
		description = description or "",
		descriptionZH = descriptionZH or "",
		items = items or {},
	}
end

