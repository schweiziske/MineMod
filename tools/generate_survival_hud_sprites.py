"""Import Java HUD effect sprites and generate Source-safe padded mappings.

python tools/generate_survival_hud_sprites.py /path/to/extracted/client
The input contains assets/minecraft/textures/gui/sprites/hud.
"""
from pathlib import Path
import argparse
import hashlib
import shutil

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPRITES = [f'heart/{kind}_{part}{blink}'
           for kind in ('poisoned', 'withered')
           for part in ('full', 'half') for blink in ('', '_blinking')]
SPRITES += [f'food_{part}_hunger' for part in ('empty', 'full', 'half')]


def generate(client: Path, root: Path = ROOT):
    source = client / 'assets/minecraft/textures/gui/sprites/hud'
    target = root / 'addons/mc_game/materials/mc/gui/sprites/hud'
    # Validate the whole input before writing resources.
    images = {}
    for name in SPRITES:
        path = source / f'{name}.png'
        image = Image.open(path).convert('RGBA')
        if image.size != (9, 9):
            raise ValueError(f'Expected a 9x9 HUD sprite: {path}: {image.size}')
        images[name] = image
    digest = hashlib.sha256()
    entries = []
    for name in sorted(SPRITES):
        path = source / f'{name}.png'
        dest = target / f'{name}.png'
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, dest)
        # Do not resize the 9x9 pixels: pad onto a transparent 16x16 canvas.
        padded = Image.new('RGBA', (16, 16))
        padded.paste(images[name], (0, 0))
        padded.save(target / f'{name}__pot.png')
        digest.update(name.encode('utf-8'))
        digest.update(path.read_bytes())
        entries.append(f'sprites["sprites/hud/{name}"] = {{ '
                       f'material = "mc/gui/sprites/hud/{name}__pot.png", '
                       'width = 9, height = 9, mappingWidth = 16, mappingHeight = 16 }')
    text = ('-- Generated by tools/generate_survival_hud_sprites.py. Do not edit by hand.\n'
            '-- Java 26.2 HUD effect sprites; source SHA256: ' + digest.hexdigest() + '\n'
            'local sprites = MC.GeneratedGuiSpriteData.sprites\n' + '\n'.join(entries) + '\n')
    output = root / 'addons/mc_game/lua/mcgame/generated/cl_generated_survival_hud_sprites.lua'
    output.write_bytes(text.replace('\n', '\r\n').encode('utf-8'))
    print(f'Generated {len(SPRITES)} original sprites, {len(SPRITES)} padded copies and mappings')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('client', type=Path)
    generate(parser.parse_args().client)
