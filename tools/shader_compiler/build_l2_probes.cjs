// Offline Stage A builder. Does not write to the game installation.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const zlib = require("node:zlib");
const { spawnSync } = require("node:child_process");
const ROOT = path.resolve(__dirname, "../..");
const ADDON = path.join(ROOT, "addons/mc_shaderpack_l2_probes");
const LUA_ADDON = path.join(ROOT, "addons/mc_engine");
const LUA_ROOT = "autorun/client";
const MANIFEST_NAME = "mc_render_l2_probe_build.lua";
const TEXTURE_ROOT = "mc_shaderpacks/l2_probes";
const tools = [
  "shadercompile.exe", "shadercompile_dll.dll", "filesystem_stdio.dll",
  "steam_api.dll", "tier0.dll", "vstdlib.dll", "fxc.exe", "dx_proxy.dll",
  "d3dx9_33.dll", "d3dcompiler_43.dll",
];
const includes = [
  "common_vs_fxc.h", "common_ps_fxc.h", "common_fxc.h",
  "common_pragmas.h", "common_hlsl_cpp_consts.h",
];
const programs = {
  vertex: ["probe_vertex.fxc", "vs_3_0"],
  slots: ["probe_slots.fxc", "ps_3_0"],
  surface: ["probe_surface.fxc", "ps_3_0"],
  sky: ["probe_sky.fxc", "ps_3_0"],
};

function fingerprint(entries) {
  const hash = crypto.createHash("sha256");
  for (const [name, bytes] of [...entries].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
    hash.update(JSON.stringify([name, bytes.length]) + "\n");
    hash.update(bytes);
  }
  return hash.digest("hex");
}

function filelistEntry(name, file, profile) {
  return [
    "**** generated by build_l2_probes.cjs ****", `#BEGIN ${name}`, file,
    "#DEFINES-D:", "#DEFINES-S:", "#SKIP:", "0", "#COMMAND:",
    "fxc.exe /DTOTALSHADERCOMBOS=1 /DCENTROIDMASK=0 /DNUMDYNAMICCOMBOS=1 /DFLAGS=0x0",
    `/T${profile} /DSHADER_MODEL_${profile.toUpperCase()}=1 /nologo /Foshader.o ${file}>output.txt 2>&1`,
    "#END", "**** end ****",
  ].join("\r\n");
}

function pngTexture(color, alternate = color) {
  function chunk(name, payload) {
    const type = Buffer.from(name);
    const length = Buffer.alloc(4);
    const checksum = Buffer.alloc(4);
    length.writeUInt32BE(payload.length);
    checksum.writeUInt32BE(zlib.crc32(Buffer.concat([type, payload])));
    return Buffer.concat([length, type, payload, checksum]);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(16, 0);
  header.writeUInt32BE(16, 4);
  header[8] = 8;
  header[9] = 6;
  const raw = Buffer.alloc(16 * (16 * 4 + 1));
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const rgb = ((x >> 3) + (y >> 3)) % 2 ? alternate : color;
      raw.set([...rgb, 255], y * 65 + 1 + x * 4);
    }
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", header), chunk("IDAT", zlib.deflateSync(raw)), chunk("IEND", Buffer.alloc(0)),
  ]);
}

function textures() {
  return [
    [[220, 80, 48], [60, 170, 220]], // s0: base
    [[32, 96, 160]],                // s1: byte sentinel, not real voxel light
    [[192, 224, 128]],              // s2: lightmap sentinel
    [[128, 128, 255], [204, 128, 230]],
    [[255, 32, 0], [128, 224, 255]], // s4: occlusion, roughness, metalness
    [[0, 0, 0], [64, 16, 96]],
    [[240, 208, 32]],
    [[32, 224, 208]],
    [[128, 128, 255]], // defaults: normal, ORM, emissive
    [[255, 255, 0]],
    [[0, 0, 0]],
  ].map(([a, b]) => pngTexture(a, b));
}

function verifyOutputs(directory, names) {
  return Object.values(names).map(name => {
    const file = path.join(directory, name + ".vcs");
    const bytes = fs.readFileSync(file);
    if (bytes.length < 32) throw new Error(`Empty/truncated shader: ${file}`);
    return [name + ".vcs", bytes];
  });
}

function main(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    if (flag === "--stage-only") flags.stageOnly = true;
    else if (["--toolchain", "--game"].includes(flag) && argv[i + 1] && !argv[i + 1].startsWith("--")) {
      flags[flag.slice(2)] = path.resolve(argv[++i]);
    } else throw new Error(`Unknown/incomplete option: ${flag}`);
  }
  const compiler = flags.toolchain || path.join(__dirname, "toolchain");
  const game = flags.game || "D:/steam/steamapps/common/GarrysMod/garrysmod";
  if (!fs.statSync(path.join(game, "gameinfo.txt")).isFile()) throw new Error("Missing gameinfo.txt");
  const source = path.join(__dirname, "shadersrc/l2/probes");
  const entries = [...tools, ...includes].map(name => [name, fs.readFileSync(path.join(compiler, name))]);
  for (const name of [...new Set(Object.values(programs).map(([file]) => file)), "probe_samplers.fxh"]) {
    entries.push([name, fs.readFileSync(path.join(source, name))]);
  }
  // Include compiler binaries, flags, generator and fixture bytes in the build identity.
  const images = textures();
  const digest = fingerprint([
    ...entries, ["builder", fs.readFileSync(__filename)],
    ["programs", Buffer.from(JSON.stringify(programs))],
    ...images.map((bytes, i) => [`texture${i}`, bytes]),
  ]);
  const id = digest.slice(0, 20);
  const names = Object.fromEntries(Object.entries(programs).map(([key, [, profile]]) =>
    [key, `mc_l2_${key}_${id}_${profile === "vs_3_0" ? "vs30" : "ps30"}`]));
  // A fresh directory prevents a failed compiler run from reusing old .vcs files.
  const parent = path.join(__dirname, ".build/l2_probes");
  fs.mkdirSync(parent, { recursive: true });
  const build = fs.mkdtempSync(path.join(parent, id + "-"));
  fs.mkdirSync(path.join(build, "shaders/fxc"), { recursive: true });
  for (const [name, bytes] of entries) fs.writeFileSync(path.join(build, name), bytes);
  fs.writeFileSync(path.join(build, "filelist.txt"), Object.entries(programs).map(([key, [file, profile]]) =>
    filelistEntry(names[key], file, profile)).join("\r\n") + "\r\n");
  fs.writeFileSync(path.join(build, "uniquefilestocopy.txt"), entries.map(([name]) => name).join("\r\n") + "\r\n");
  console.log(`Build ${digest}\nStaging: ${build}`);
  if (flags.stageOnly) return;
  const result = spawnSync(path.join(build, "shadercompile.exe"), [
    "-nompi", "-allowdebug", "-game", game, "-shaderpath", build,
  ], { cwd: build, encoding: "utf8", windowsHide: true, timeout: 180000 });
  fs.writeFileSync(path.join(build, "compiler.log"), (result.stdout || "") + (result.stderr || ""));
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Compiler exit ${result.status}; see ${build}/compiler.log`);
  const output = verifyOutputs(path.join(build, "shaders/fxc"), names);
  const addon = ADDON;
  const shaderDir = path.join(addon, "shaders/fxc");
  const textureDir = path.join(addon, "materials", TEXTURE_ROOT, id);
  const manifest = path.join(LUA_ADDON, "lua", LUA_ROOT, MANIFEST_NAME);
  fs.mkdirSync(shaderDir, { recursive: true });
  fs.mkdirSync(textureDir, { recursive: true });
  fs.mkdirSync(path.dirname(manifest), { recursive: true });
  for (const [name, bytes] of output) {
    const target = path.join(shaderDir, name);
    if (fs.existsSync(target) && !fs.readFileSync(target).equals(bytes)) {
      throw new Error(`Build-name collision; refusing to overwrite ${target}`);
    }
  }
  for (const [name, bytes] of output) fs.writeFileSync(path.join(shaderDir, name), bytes);
  images.forEach((bytes, i) => fs.writeFileSync(path.join(textureDir, `${i}.png`), bytes));
  const lua = "-- Generated by tools/shader_compiler/build_l2_probes.cjs. Probe-only autorun data, not a pack API.\nMC_L2ProbeBuild = {\n" +
    `    id = "${id}",\n    fingerprint = "${digest}",\n` +
    Object.entries(names).map(([key, name]) => `    ${key} = "${name}",\n`).join("") +
    `    textureRoot = "${TEXTURE_ROOT}/${id}/",\n}\n`;
  fs.writeFileSync(manifest + ".tmp", lua);
  fs.renameSync(manifest + ".tmp", manifest);
  console.log(`Published ${output.length} shaders and ${images.length} PNGs to ${addon}`);
  console.log(`Probe Lua manifest: ${manifest}`);
}

module.exports = { fingerprint, filelistEntry, pngTexture, textures, verifyOutputs, ADDON, LUA_ADDON, LUA_ROOT, MANIFEST_NAME, TEXTURE_ROOT };
if (require.main === module) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
