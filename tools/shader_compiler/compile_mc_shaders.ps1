function Resolve-FullPath {
	param([string]$PathValue)
	return [System.IO.Path]::GetFullPath($PathValue)
}

function Assert-PathInsideWorkspace {
	param([string]$PathValue)
	$root = Resolve-FullPath $WorkspaceRoot
	$full = Resolve-FullPath $PathValue
	if (-not $full.StartsWith($root, [System.StringComparison]::OrdinalIgnoreCase)) {
		throw "Refusing to operate outside workspace: $full"
	}
}

function Assert-FileExists {
	param([string]$PathValue, [string]$Label)
	if (-not (Test-Path -LiteralPath $PathValue -PathType Leaf)) {
		throw "$Label not found: $PathValue"
	}
}

function Assert-DirectoryExists {
	param([string]$PathValue, [string]$Label)
	if (-not (Test-Path -LiteralPath $PathValue -PathType Container)) {
		throw "$Label not found: $PathValue"
	}
}

function New-ShaderFileListEntry {
	param(
		[string]$ShaderName,
		[string]$FileName,
		[string]$TargetProfile,
		[string]$ExtraDefines = ""
	)

	$profileDefine = "SHADER_MODEL_" + ($TargetProfile.ToUpperInvariant() -replace "_", "_")
	$extra = if ($ExtraDefines -and $ExtraDefines.Trim() -ne "") { " " + $ExtraDefines.Trim() } else { "" }
	return @"
**** generated by compile_mc_shaders.ps1 ****
#BEGIN $ShaderName
$FileName
#DEFINES-D:
#DEFINES-S:
#SKIP:
0
#COMMAND:
fxc.exe /DTOTALSHADERCOMBOS=1 /DCENTROIDMASK=0 /DNUMDYNAMICCOMBOS=1 /DFLAGS=0x0
/T$TargetProfile /D$profileDefine=1$extra /nologo /Foshader.o $FileName>output.txt 2>&1
#END
**** end ****
"@
}

