[CmdletBinding(SupportsShouldProcess = $true)]
param(
	[string] $RepositoryRoot,
	[switch] $NoPause
)

$ErrorActionPreference = "Stop"
try {
	if (-not $PSBoundParameters.ContainsKey("RepositoryRoot")) {
		$RepositoryRoot = Join-Path $PSScriptRoot ".."
	}
	$repository = (Resolve-Path -LiteralPath $RepositoryRoot).Path
	$addonsRoot = Join-Path $repository "addons"
	$outputRoot = Join-Path $repository "minemod"
	$markerName = ".minemod-generated"

	if (-not (Test-Path -LiteralPath $addonsRoot -PathType Container)) {
		throw "Addon directory not found: $addonsRoot"
	}

	function Convert-GlobToRegex([string] $Pattern) {
		$pattern = $Pattern.Replace("\", "/").TrimStart("/")
		if ($pattern.EndsWith("/")) { $pattern += "**" }
		$builder = New-Object System.Text.StringBuilder
		for ($index = 0; $index -lt $pattern.Length; $index++) {
			$character = $pattern[$index]
			if ($character -eq "*" -and $index + 1 -lt $pattern.Length -and $pattern[$index + 1] -eq "*") {
				if ($index + 2 -lt $pattern.Length -and $pattern[$index + 2] -eq "/") {
					[void] $builder.Append("(?:.*/)?")
					$index += 2
				} else {
					[void] $builder.Append(".*")
					$index++
				}
			} elseif ($character -eq "*") {
				[void] $builder.Append("[^/]*")
			} elseif ($character -eq "?") {
				[void] $builder.Append("[^/]")
			} else {
				[void] $builder.Append([regex]::Escape([string] $character))
			}
		}
		return "^(?:" + $builder.ToString() + ")$"
	}

	function Test-IgnoredPath([string] $RelativePath, [string[]] $Patterns) {
		foreach ($pattern in $Patterns) {
			if ([regex]::IsMatch($RelativePath, (Convert-GlobToRegex $pattern), [System.Text.RegularExpressions.RegexOptions]::IgnoreCase)) {
				return $true
			}
		}
		return $false
	}

	$filesByPath = @{}
	$ignoredCount = 0
	foreach ($addon in (Get-ChildItem -LiteralPath $addonsRoot -Directory | Sort-Object Name)) {
		$manifestPath = Join-Path $addon.FullName "addon.json"
		$ignorePatterns = @()
		if (Test-Path -LiteralPath $manifestPath -PathType Leaf) {
			$manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
			if ($manifest.ignore) { $ignorePatterns = @($manifest.ignore | ForEach-Object { [string] $_ }) }
		}

		foreach ($file in (Get-ChildItem -LiteralPath $addon.FullName -File -Recurse -Force | Sort-Object FullName)) {
			if ($file.Name -eq "addon.json") { continue }
			$relativePath = $file.FullName.Substring($addon.FullName.Length + 1).Replace("\", "/")
			if (Test-IgnoredPath $relativePath $ignorePatterns) {
				$ignoredCount++
				continue
			}

			$key = $relativePath.ToLowerInvariant()
			if ($filesByPath.ContainsKey($key)) {
				$existing = $filesByPath[$key]
				throw "Conflicting files map to '$relativePath': '$($existing.Source)' and '$($file.FullName)'"
			}
			$filesByPath[$key] = [PSCustomObject]@{
				RelativePath = $relativePath
				Source = $file.FullName
			}
		}
	}

	if (Test-Path -LiteralPath $outputRoot) {
		$existingOutput = Get-Item -LiteralPath $outputRoot -Force
		if (-not $existingOutput.PSIsContainer -or $existingOutput.Attributes -band [IO.FileAttributes]::ReparsePoint) {
			throw "Refusing to replace a non-directory or linked output path: $outputRoot"
		}
		if (-not (Test-Path -LiteralPath (Join-Path $outputRoot $markerName) -PathType Leaf)) {
			throw "Refusing to replace '$outputRoot' because it is not marked as generated by this script."
		}
	}

	if (-not $PSCmdlet.ShouldProcess($outputRoot, "Merge $($filesByPath.Count) files from addons into minemod")) {
		return
	}

	$stageRoot = Join-Path $repository (".minemod-stage-" + [guid]::NewGuid().ToString("N"))
	$backupRoot = $null
	try {
		New-Item -ItemType Directory -Path $stageRoot | Out-Null
		foreach ($entry in ($filesByPath.Values | Sort-Object RelativePath)) {
			$destination = Join-Path $stageRoot ($entry.RelativePath.Replace("/", [IO.Path]::DirectorySeparatorChar))
			$destinationDirectory = Split-Path -Parent $destination
			New-Item -ItemType Directory -Path $destinationDirectory -Force | Out-Null
			Copy-Item -LiteralPath $entry.Source -Destination $destination
		}

		$mergedManifest = [ordered]@{
			title = "MineMod"
			type = "tool"
			tags = @("build", "fun")
			ignore = @("*.md", "**/*.md", $markerName)
		}
		$manifestJson = $mergedManifest | ConvertTo-Json -Depth 8
		$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
		[IO.File]::WriteAllText((Join-Path $stageRoot "addon.json"), $manifestJson + "`n", $utf8NoBom)
		[IO.File]::WriteAllText((Join-Path $stageRoot $markerName), "Generated by tools/merge_addons.ps1`n", $utf8NoBom)

		if (Test-Path -LiteralPath $outputRoot) {
			$backupRoot = Join-Path $repository (".minemod-backup-" + [guid]::NewGuid().ToString("N"))
			Move-Item -LiteralPath $outputRoot -Destination $backupRoot
		}
		Move-Item -LiteralPath $stageRoot -Destination $outputRoot
		$stageRoot = $null
		if ($backupRoot) {
			Remove-Item -LiteralPath $backupRoot -Recurse -Force
			$backupRoot = $null
		}

		Write-Host "Merge complete: $($filesByPath.Count) files, $ignoredCount ignored. Output: $outputRoot"
		[PSCustomObject]@{
			Output = $outputRoot
			Files = $filesByPath.Count
			Ignored = $ignoredCount
		}
	} catch {
		if ($backupRoot -and (Test-Path -LiteralPath $backupRoot) -and -not (Test-Path -LiteralPath $outputRoot)) {
			Move-Item -LiteralPath $backupRoot -Destination $outputRoot
			$backupRoot = $null
		}
		throw
	} finally {
		if ($stageRoot -and (Test-Path -LiteralPath $stageRoot)) {
			Remove-Item -LiteralPath $stageRoot -Recurse -Force
		}
	}
} catch {
	Write-Host ("Merge failed: {0}" -f $_) -ForegroundColor Red
	throw
} finally {
	if (-not $NoPause) {
		Read-Host "Press Enter to close" | Out-Null
	}
}
